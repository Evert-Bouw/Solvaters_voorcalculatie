export function buildQuotationLineFieldMappings(settings: Settings): QuotationLineFieldMapping[] {
  const configurableFieldIds = settings.quotationLineConfigurableAfasIds ?? {};
  const resolvedFixedFields = FIXED_FIELDS.map((field) => {
    if (field.afasMode !== 'configurable') {
      const { afasFieldId, ...rest } = field;
      return { ...rest, ...(afasFieldId ? { afasFieldId } : {}) };
    }
    const fieldId = configurableFieldIds[field.appFieldId]?.trim() ?? '';
    return {
      ...field,
      afasFieldId: fieldId || undefined,
      afasFieldLabel: fieldId || undefined,
      afasPath: fieldId ? `KnQuotationLine.Fields.${fieldId}` : undefined,
    };
  });

  const markupMappings: QuotationLineFieldMapping[] = settings.markupOrder.map((type, index) => {
    const afasFieldId = settings.lineMarkupAfasIds[type]?.trim() ?? '';
    return {
      appFieldId: `QL-MARKUP-${type}`,
      appStorageKey: `markup${type}`,
      appLabel: settings.lineMarkupDescriptions[type] ?? `Vrije opslag kolom ${index + 1}`,
      valueType: 'number',
      afasMode: 'configurable',
      afasPath: afasFieldId ? `KnQuotationLine.Fields.${afasFieldId}` : undefined,
      afasFieldId: afasFieldId || undefined,
      afasFieldLabel: afasFieldId || undefined,
      source: 'settings',
      notes: afasFieldId
        ? 'Vrije opslagkolom; AFAS-veld komt uit instellingen.'
        : 'Vrije opslagkolom; vul eerst een AFAS ID in om deze naar AFAS te kunnen schrijven.',
    };
  });

  return [...resolvedFixedFields, ...markupMappings];
}
